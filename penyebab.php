            <p>Tanah longsor terjadi karena gaya pendorong pada lereng lebih besar dari gaya penahan. Gaya penahan 
                umumnya dipengaruhi oleh kekuatan batuan dan kepadatan tanah. Adapun gaya pendorong dipengaruhi 
                oleh besar sudut lereng, air, beban serta berat jenis tanah batuan.</p>
            <p></p>
            <h4>Faktor-faktor penyebab terjadinya tanah longsor</h4>
            <h5>1. Curah Hujan</h5>
            <p>Hujan lebat pada awal musim dapat menyebabkan bencana longsor karena air akan masuk ke tanah dan terakumulasi di bagian dasar lereng, sehingga menimbulkan gerakan lateral.</p>
            <h5>2. Erosi </h5>
            <p>Erosi merupakan pengikisan tanah yang disebabkan aliran air permukaan atau air hujan, sungai-sungai atau gelombang laut yang menggerus lereng tanah. Air yang menggerus lereng-lereng ini akhirnya bertambah curam dan menjadi penyebab longsor.</p>
            <h5>3. Perubahan Air Tanah</h5>
            <p>Perubahan air pada tanah yang disebabkan oleh hujan maupun oleh aliran air yang masuk dan memenuhi rongga mengakibatkan terjadinya pergeseran tanah, yang kemudian menyebabkan terjadinya erosi tanah dan longsor.</p>
            <h5>4. Gempa Bumi</h5>
            <p>Gempa bumi merupakan salah satu penyebab longsor yang sering terjadi. Gempa bumi menyebabkan getaran, tekanan pada partikel-partikel mineral dan bidang lemah pada massa batuan dan tanah. Ini menyebabkan longsornya lereng-lereng di tebing atau gunung</p>
            <h5>5. Aktivitas Gunung Berapi</h5>
            <p>Gunung berapi menciptakan simpanan debu yang lengang, hujan lebat dan aliran debu-debu. Ini bisa menyebabkan getaran atau pergolakan tanah yang menjadi penyebab longsor</p>
            <h5>6. Gangguan Oleh Aktivitas Manusia</h5>
            <p>Aktivitas manusia seperti pertambangan, lalu lintas, dan proyek dengan menggunakan bahan peledak dapat mengakibatkan getaran.</p>
            <p>Getaran yang disebabkan oleh adanya lalu lintas kendaraan di area lereng perbukitan secara tidak langsung dapat mengakibatkan tanah longsor. 
               Karena, jalanan di lereng bukit yang sering dilewati kendaraan akan perlahan mengalami keretakan. Sedangkan bahan peledak dan pertambangan yang menggunakan mesin juga bisa menjadi penyebab dari longsor
               dikarenakan getaran yang dihasilkan oleh aktivitas ini menyebabkan gaya penahan pada tanah berkurang.</p>
            <h5>7. Penggundulan Hutan</h5>
            <p>Penyebab longsor selanjutnya disebabkan oleh ulah manusia. Pepohonan di lereng, tebing, gunung, atau bukit berfungsi untuk menyerap air agar mencegah erosi tanah. Jika sebuah area, terutama area lereng dan tebing tidak memiliki cukup pepohonan, 
               ini akan menyebabkan terjadinya tanah longsor. Hutan gundul akan memengaruhi struktur tanah yang melonggar karena tidak memiliki penahan, juga air tidak memiliki daerah resapan.</p>
